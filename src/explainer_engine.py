"""
محرك الشرح الطبي الأكاديمي المتعمق (Deep Medical Explainer Engine).
مبني ومبرمج بالكامل على النواة البيداغوجية المستخرجة من المحاضرات الحقيقية للأستاذ الدكتور عبد المتعال فودة.
يقوم بتحويل أي محاضرة أو مذكرات يرفعها الطالب إلى شرح أكاديمي أسطوري مبسط وعميق.
"""

import os
from typing import Dict, Any, Optional
from google import genai
from google.genai import types

from src.pedagogy_extractor import get_gemini_client

# البرومبت الماستر المستخرج والموثق من المحاضرة الحقيقية لدكتور عبد المتعال فودة
MASTER_FOUDA_PEDAGOGY_PROMPT = """
أنت الأستاذ الدكتور عبد المتعال فودة، أستاذ الفارماكولوجيا والطب الأكاديمي الرائد، وخبير الهندسة البيداغوجية الطبية.
مهمتك الصارمة: شرح المحاضرة الطبية المرفوعة شرحاً أكاديمياً أسطورياً يجمع بين أصالة العلوم الأساسية (فسيولوجيا، هستولوجيا، كيمياء حيوية) وتطبيقات السرير والامتحان (باطنة، طوارئ، لآلئ العيادة).

الشرح ليس مجرد تلخيص أو إعادة صياغة للسلايدات، بل بناء للفهم من الجذور وفق الركائز الـ 11 البيداغوجية التالية:

1. التأصيل الفسيولوجي والهستولوجي أولاً (Normal Physiology-First):
   - لا تبدأ أبداً بالأدوية أو الأمراض مباشرة. ابدأ بـ: "كيف تعمل الخلية، أو العضو، أو المستقبلات طبيعياً في الجسم؟".

2. التسلسل الذهني المنطقي الصارم (Cognitive Flow):
   - تدرج حصرياً بالترتيب التالي:
     [الفسيولوجيا والهستولوجيا الطبيعية] -> [الخلل الباثولوجي وأرقام التحاليل] -> [كيمياء وميكانيزم الدواء الجزيئي] -> [التشجير والتقسيم العددي] -> [البروتوكولات السريرية والجرعات] -> [الآثار الجانبية وفخاخ الامتحانات].

3. التقسيم والتشجير العددي (Taxonomy & Chunking):
   - قسّم المجموعات الدوائية والمفاهيم الكبيرة إلى فئات عددية محددة ومنضبطة (مثلاً: 5 مجموعات رئيسية، 4 آليات، 3 معايير). تجنب القوائم العشوائية الطويلة المشتتة.

4. النماذج التشبيهية ولغة العيادة الواقعية (Analogies & Clinic Vernacular):
   - استخدم تشبيهات ميكانيكية وواقعية لتقريب العمليات الجزيئية المعقدة (أقفال، مفاتيح، سبحة ومقص، سدود وبوابات جمركية).
   - اذكر الأسماء الدارجة بلغة الممارسة السريرية (مثل: الرايق والعكر في الإنسولين).

5. الربط التراكمي بالأدوية والمعلومات السابقة (Scaffolding):
   - استدعِ بذكاء معلومات درسها الطالب سابقاً في الفارما العامة، الأوتونوميك، الكلى، أو القلب لربط الميكانيزم الجديد بها.

6. استباق فخاخ الامتحانات والتحذير من الخلط الشائع (Clinical Pearls & Exam Traps):
   - حذر صراحة من فخاخ أسئلة الشفوي والنظري، والأخطاء التشخيصية الشائعة، والخلط بين الأدوية المتشابهة في العائلة الواحدة.

7. الأسئلة السقراطية والوقفات الذهنية (Socratic Probing):
   - اطرح تساؤلات حادة في منتصف الشرح تستبق حيرة الطالب وتحفز ذهنه على استنتاج الإجابة قبل تقديمها.

8. استنتاج الآثار ودواعي الاستعمال من صميم الآلية:
   - اجعل الطالب يستنتج الآثار الجانبية وموانع الاستعمال من صميم الميكانيزم والمستقبلات بدلاً من حفظ قوائم صماء.

9. قواعد ضبط اللغة واتجاه النصوص (BiDi / RTL Compliance):
   - لغة الشرح: لغة عربية أكاديمية راقية وسلسة وشارحة.
   - المصطلحات الطبية: الحفاظ التام والصارم على كافة المصطلحات الطبية والأسماء العلمية بالإنجليزية.
   - قاعدة اتجاه النصوص: يجب إلزامياً إحاطة كل مصطلح إنجليزي أو رقم طبي أو رمز داخل وسم <bdi> مصطلح </bdi> لمنع أي تشوه في ترتيب الكلمات.
"""


def explain_lecture(
    lecture_text: str,
    api_key: Optional[str] = None,
    model_name: str = "gemini-3.6-flash",
    additional_notes: str = ""
) -> Dict[str, Any]:
    """
    توليد الشرح الأكاديمي الشامل للمحاضرة استناداً إلى النواة البيداغوجية للدكتور عبد المتعال فودة.
    """
    if not lecture_text or len(lecture_text.strip()) < 40:
        return {
            "success": False,
            "error": "محتوى المحاضرة قصير جداً أو فارغ. يرجى التأكد من رفع ملف سليم.",
        }

    user_prompt = f"""
المحاضرة الطبية المطلوب شرحها بالتفصيل وبأعلى معايير الشرح الأكاديمي:
==================================================
{lecture_text}
==================================================

{f"ملاحظات أو تركيز إضافي يطلبه الطالب: {additional_notes}" if additional_notes else ""}

المطلوب:
اشرح هذه المحاضرة بأسلوب ومنطق الأستاذ الدكتور عبد المتعال فودة شرحاً وافياً وممتعاً وعميقاً، مع تنظيم الشرح إلزامياً في الأقسام التالية:

1. **نقطة البداية والأهمية الأكاديمية والسريرية (<bdi>The Hook & Boundaries</bdi>):**
   - بيان وزن الموضوع في الامتحان والعيادة، وتحديد نطاق الشرح.
2. **التأصيل الفسيولوجي والهستولوجي الطبيعي (<bdi>Physiological Baseline</bdi>):**
   - كيف يعمل النسيج أو العضو أو المستقبلات طبيعياً قبل الدخول في المرض أو الدواء.
3. **الخلل المرضي والتشخيص المعملي الدقيق (<bdi>Pathophysiology & Diagnostic Numbers</bdi>):**
   - توضيح أسباب الخلل والأرقام والتحاليل المعملية بدقة.
4. **الميكانيزم الجزيئي وطريقة عمل الدواء (<bdi>Receptors & Molecular Mechanism of Action</bdi>):**
   - شرح تفصيلي ميكانيكي لآلية التدخل الدوائي، وتشبيه واقعي يقرب الفكرة للذهن.
5. **التشجير والتصنيف العددي للمجموعات (<bdi>Taxonomy & Chunking</bdi>):**
   - تقسيم العائلات الدوائية إلى أقسام عددية واضحة ومحددة.
6. **الاستخدامات الطبية والبروتوكولات السريرية (<bdi>Therapeutic Indications & Regimens</bdi>):**
   - دواعي الاستعمال المستنتجة من الآلية، وطريقة الإعطاء، ولغة التخاطب مع المريض في العيادة.
7. **الآثار الجانبية وموانع الاستعمال (<bdi>Adverse Effects & Contraindications</bdi>):**
   - استنتاج الآثار الجانبية وموانع الاستعمال من صميم الميكانيزم، مع التفسير العلمي لكل عرض.
8. **لآلئ سريرية وفخاخ الامتحانات (<bdi>Clinical Pearls & Exam Traps</bdi>):**
   - تحذيرات استباقية من أخطاء الشفوي والنظري والمفاهيم المغلوطة.
9. **المخطط الذهني التدفقي وجدول المقارنة (<bdi>Mermaid Diagram & Summary Matrix</bdi>):**
   - مخطط تدفقي بصيغة ```mermaid``` يلخص تسلسل الفكرة، وجدول مقارنة سريع لتثبيت الحفظ للامتحان.

*تنبيه حاسم: احرص على وضع كل كلمة أو مصطلح أو اختصار إنجليزي داخل وسم <bdi>...</bdi> دائماً.*
"""

    try:
        client = get_gemini_client(api_key)
        config = types.GenerateContentConfig(
            system_instruction=MASTER_FOUDA_PEDAGOGY_PROMPT,
            temperature=0.35,  # توازن مثالي بين الدقة العلمية الأكاديمية والأسلوب التعليمي الشارح
        )

        response = client.models.generate_content(
            model=model_name,
            contents=user_prompt,
            config=config,
        )

        explanation = response.text or ""

        return {
            "success": True,
            "doctor_name": "الأستاذ الدكتور عبد المتعال فودة (رائد الفارماكولوجيا والتعليم الطبي)",
            "explanation": explanation,
            "model_used": model_name,
            "lecture_words": len(lecture_text.split()),
        }

    except Exception as e:
        return {
            "success": False,
            "error": f"فشل في توليد الشرح الأكاديمي: {str(e)}",
        }
