import os
import json
from dotenv import load_dotenv
from google import genai
from google.genai import types

load_dotenv()

api_key = os.getenv("GEMINI_API_KEY")
if not api_key:
    raise ValueError("GEMINI_API_KEY not found in .env")

client = genai.Client(api_key=api_key)

with open("data/transcripts/dr_fouda_diabetes_insulin.txt", "r", encoding="utf-8") as f:
    transcript_text = f.read()

prompt = f"""
أنت خبير أرقى في "الهندسة البيداغوجية والتعليم الطبي الأكاديمي".
أمامك التفريغ النصي الحقيقي الكامل لمحاضرة الأستاذ الدكتور عبد المتعال فودة (أستاذ الفارماكولوجيا بطب المنصورة) في موضوع:
Endocrine Pharmacology - Diabetes Mellitus & Insulin.

التفريغ يحتوي على 17,163 كلمة حقيقية منطوقة.

المطلوب منك تحليل وتفكيك هذه المحاضرة إلى ثلاثة أقسام جوهرية، مع الاستناد الدقيق لنص المحاضرة وأمثلة حقيقية منها:

==================================================
القسم الأول: ما هو الموضوع والماتيريال التي تم شرحها؟ (What was taught)
==================================================
1. العنوان الطبي الدقيق والموضع الأكاديمي في المنهج.
2. المفاهيم والحقائق الطبية الأساسية التي تناولها الدكتور في المحاضرة (مثل: تعريف السكر، التفرقة بين النوع الأول والثاني، أهمية الـ C-peptide، تصنيع وإفراز الإنسولين، تحكم الجهاز العصبي، ميكانيزم مستقبلات الـ Tyrosine Kinase، التأثيرات الأيضية على الكربوهيدرات والدهون والبروتينات والبوتاسيوم، وأنواع ومستحضرات الإنسولين، والآثار الجانبية).
3. ما هي الحدود التي وضعها لنفسه؟ (ماذا شرح وماذا ترك لأساتذة الباطنة).

==================================================
القسم الثاني: كيف شُرحت؟ (منطق وتكنيك الشرح - الركائز الـ 11) (How it was taught)
==================================================
أجب عن كل ركيزة بدقة مع الاستشهاد بعبارات وأمثلة واقتباسات حقيقية من النص:
1. نقطة البداية (The Hook): كيف افتتح المحاضرة وشد انتباه الطالب؟
2. ترتيب بناء الفكرة (Cognitive Flow): كيف تسلسل منطقياً من الفسيولوجيا الطبيعية إلى الدواء ثم الآثار الجانبية؟
3. طريقة التقسيم والتشجير (Taxonomy & Chunking): كيف قسم الموضوع الكبير (مثل مستحضرات الإنسولين أو أنواع السكر) إلى فئات واضحة؟
4. نوع الأمثلة والتشبيهات (Analogies & Mental Models): ما هي التشبيهات الواقعية والميكانيكية التي استخدمها لتقريب الفكرة؟
5. الربط التراكمي (Scaffolding): كيف استدعى معلومات سابقة درسها الطالب ليربط بها (مثل مستقبلات الـ Autonomic وتأثير Alpha و Beta على إفراز الإنسولين)؟
6. استباق اللبس وفخاخ الامتحانات (Differential Logic & Pitfalls): أين حذر الدكتور من أخطاء شائعة أو أسئلة خبيثة في الامتحان والعيادة؟
7. توقيت الربط بالتطبيق السريري (Clinical Relevance): متى وأين ربط بالواقع العملي والمستشفى؟
8. تسلسل طرح المصطلحات الطبية (Terminology Sequence): كيف مزج بين الشرح والتبسيط بالعربي وذكر المصطلح الطبي الإنجليزي بدقة؟
9. التلخيص وتثبيت الذاكرة (Retention & Wrap-up): كيف يلخص النقاط المهمة ويعيد تثبيتها؟
10. الأسئلة السقراطية والوقفات الذهنية (Socratic Probing): ما هي التساؤلات التي ألقاها لتحفيز ذهن الطالب أثناء الشرح؟
11. البناء الهيكلي المرئي (Mental Schematics): كيف رسم في ذهن الطالب شجرة أو جدول مقارنة؟

==================================================
القسم الثالث: البرومبت التنفيذي الأساسي (Master Pedagogical System Prompt)
==================================================
قم بصياغة البرومبت التنفيذي (System Instruction) الكامل الذي يمثل "عقل الأداة".
هذا البرومبت يجب أن يكون جاهزاً للحقن في نموذج الذكاء الاصطناعي بحيث عندما يرفع أي طالب طب أي محاضرة جديدة (في الفارما أو غيرها)، يتقمص الذكاء الاصطناعي ذات المنطق، التسلسل، التأصيل الفسيولوجي، ونبرة الأستاذ المحنك التي تجلت في هذا التحليل.

--------------------------------------------------
نص التفريغ الكامل:
{transcript_text}
"""

print("Sending 17,000+ words transcript to Gemini 3.6 Flash for deep pedagogical analysis...")

response = client.models.generate_content(
    model="gemini-3.6-flash",
    contents=prompt,
    config=types.GenerateContentConfig(
        temperature=0.2, # حرارة منخفضة جداً للالتزام الصارم بالنص
    )
)

result_text = response.text or ""

# حفظ التحليل كملف ماركداون مفصل
with open("data/dr_fouda_real_analysis.md", "w", encoding="utf-8") as f:
    f.write(result_text)

print(f"Analysis completed and saved successfully! Length: {len(result_text)} chars, {len(result_text.split())} words.")
